"""Generate JSON Schema and TypeScript types from the Pydantic models (single source of truth, spec 2.10).

Usage: python scripts/gen_types.py [--check]
Writes docs/schema/glassbox.schema.json and frontend/src/types/generated.ts. With --check it only verifies
that the committed files are up to date (exit 1 otherwise).
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

from pydantic import BaseModel, TypeAdapter

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))

from glassbox.schemas import analysis, api, events

SCHEMA_PATH = ROOT / "docs" / "schema" / "glassbox.schema.json"
TS_PATH = ROOT / "frontend" / "src" / "types" / "generated.ts"
HEADER = "// GENERATED by scripts/gen_types.py from backend/glassbox/schemas/ - do not edit by hand.\n"


def _models(*modules: Any) -> list[type[BaseModel]]:
    found: dict[str, type[BaseModel]] = {}
    for module in modules:
        for name in sorted(vars(module)):
            obj = getattr(module, name)
            if (
                isinstance(obj, type)
                and issubclass(obj, BaseModel)
                and obj.__module__ == module.__name__
                and not name.startswith("_")
            ):
                found[name] = obj
    return list(found.values())


def build_schema() -> dict[str, Any]:
    defs: dict[str, Any] = {}
    for model in _models(events, api, analysis):
        schema = model.model_json_schema(mode="validation", ref_template="#/$defs/{model}")
        defs.update(schema.pop("$defs", {}))
        defs[model.__name__] = schema
    union = TypeAdapter(events.RunEvent).json_schema(mode="validation", ref_template="#/$defs/{model}")
    union_defs = union.pop("$defs", {})
    for key, value in union_defs.items():
        defs.setdefault(key, value)
    defs["RunEvent"] = union
    return {"$schema": "https://json-schema.org/draft/2020-12/schema", "$defs": dict(sorted(defs.items()))}


# ----------------------------------------------------------------------------------------------- TypeScript
def _lit(value: Any) -> str:
    return json.dumps(value)


def ts_type(node: dict[str, Any]) -> str:
    if "$ref" in node:
        return node["$ref"].rsplit("/", 1)[-1]
    if "const" in node:
        return _lit(node["const"])
    if "enum" in node:
        return " | ".join(_lit(v) for v in node["enum"])
    for key in ("anyOf", "oneOf"):
        if key in node:
            parts = [ts_type(n) for n in node[key]]
            return " | ".join(dict.fromkeys(parts))
    kind = node.get("type")
    if isinstance(kind, list):
        return " | ".join(dict.fromkeys(ts_type({**node, "type": k}) for k in kind))
    if kind == "string":
        return "string"
    if kind in ("integer", "number"):
        return "number"
    if kind == "boolean":
        return "boolean"
    if kind == "null":
        return "null"
    if kind == "array":
        if "prefixItems" in node:
            return "[" + ", ".join(ts_type(n) for n in node["prefixItems"]) + "]"
        return f"Array<{ts_type(node['items'])}>" if "items" in node else "unknown[]"
    if kind == "object" or "properties" in node:
        return _object(node)
    return "unknown"


def _object(node: dict[str, Any]) -> str:
    props = node.get("properties", {})
    extra = node.get("additionalProperties")
    if not props:
        if isinstance(extra, dict):
            return f"{{ [key: string]: {ts_type(extra)} }}"
        return "Record<string, unknown>"
    # A Literal with a default (``type``, ``v``) is always present on the wire, so it is required for TS narrowing.
    required = set(node.get("required", [])) | {n for n, sch in props.items() if "const" in sch}
    lines = [f"  {_lit(name)}{'' if name in required else '?'}: {ts_type(schema)};" for name, schema in props.items()]
    return "{\n" + "\n".join(lines) + "\n}"


def build_ts(schema: dict[str, Any]) -> str:
    out = [HEADER]
    for name, node in schema["$defs"].items():
        if node.get("type") == "object" and "properties" in node:
            body = _object(node).replace("\n", "\n")
            out.append(f"export interface {name} {body}\n")
        else:
            out.append(f"export type {name} = {ts_type(node)};\n")
    return "\n".join(out)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail if the generated files are out of date")
    args = parser.parse_args()
    schema = build_schema()
    schema_text = json.dumps(schema, indent=2, sort_keys=True) + "\n"
    ts_text = build_ts(schema)
    if args.check:
        stale = [
            str(p.relative_to(ROOT))
            for p, text in ((SCHEMA_PATH, schema_text), (TS_PATH, ts_text))
            if not p.exists() or p.read_text(encoding="utf-8") != text
        ]
        if stale:
            print("out of date (run `make schema`): " + ", ".join(stale), file=sys.stderr)
            return 1
        return 0
    for path, text in ((SCHEMA_PATH, schema_text), (TS_PATH, ts_text)):
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
